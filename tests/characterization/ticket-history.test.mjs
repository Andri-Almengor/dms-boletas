import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = (path) => readFileSync(new URL('../../' + path, import.meta.url), 'utf8');

test('ticket edits and autosaves share transactionally persisted snapshots under row lock', () => {
  const ticket = read('backend/src/modules/tickets.module.js');
  const audit = read('backend/src/services/audit.service.js');
  assert.match(ticket, /function persistTicketEdit\(ctx, autosave = false\)/);
  assert.match(ticket, /FOR UPDATE/);
  assert.match(ticket, /AUTOGUARDAR_BOLETA/);
  assert.match(ticket, /assignedTicketSnapshot/);
  assert.match(ticket, /immediate: true/);
  assert.match(ticket, /update: async \(ctx\) => enrichTicket\(await persistTicketEdit\(ctx\)\)/);
  assert.match(ticket, /await persistTicketEdit\(ctx, true\)/);
  assert.match(audit, /if \(immediate\) \{[\s\S]*await appendRow\('Auditoria', row\)/);
  assert.match(ticket, /ORDER BY "Fecha" DESC, "__db_id" DESC LIMIT \$2 OFFSET \$3/);
  assert.match(read('backend/migrations/027_ticket_edit_audit_history_index.sql'), /CREATE INDEX IF NOT EXISTS/);
});

test('management-only ticket history opens in its own tab and stays read-only', () => {
  const router = read('backend/src/core/action-router.js');
  const app = read('src/app/App.jsx');
  const detail = read('src/pages/tickets/TicketDetailPage.jsx');
  const page = read('src/pages/tickets/TicketHistoryPage.jsx');
  const viewer = read('src/components/tickets/TicketHistoryPanel.jsx');
  const styles = read('src/styles/ticket-history.css');
  assert.match(router, /ticketHandlers\.history, 'USUARIOS_GESTIONAR'/);
  assert.match(app, /path="boletas\/:boletaUid\/historial" element=\{<PermissionRoute permission="USUARIOS_GESTIONAR">/);
  assert.match(detail, /hasPermission\('USUARIOS_GESTIONAR'\) && \(/);
  assert.match(detail, /to=\{`\/boletas\/\$\{encodeURIComponent\(boletaUid\)\}\/historial`\}/);
  assert.match(detail, /target="_blank" rel="noopener noreferrer"/);
  assert.match(detail, /ticket-history-launch__action/);
  assert.doesNotMatch(detail, /<TicketHistoryPanel/);
  assert.match(page, /<TicketHistoryPanel boletaUid=\{boletaUid\} sessionToken=\{sessionToken\}/);
  assert.match(viewer, /void loadHistory\(1\)/);
  assert.match(viewer, /function TicketHistoryComparison\(/);
  assert.match(viewer, /function TicketHistoryValue\(/);
  assert.match(viewer, /aria-label="Comparación de versiones de la boleta"/);
  assert.match(viewer, /Antes <small>Versión anterior<\/small>/);
  assert.match(viewer, /Después <small>Versión guardada<\/small>/);
  assert.match(viewer, /aria-pressed=\{!showAll\}/);
  assert.match(viewer, /aria-pressed=\{showAll\}/);
  assert.match(viewer, /Solo cambios/);
  assert.match(viewer, /Todos los campos/);
  assert.match(viewer, /fields=\{showAll \? fields : changed\}/);
  assert.match(viewer, /No conservado en el registro/);
  assert.match(viewer, /Registro parcial/);
  assert.match(viewer, /ticket-history-diff__mobile-label/);
  assert.match(viewer, /campos modificados/);
  assert.match(viewer, /pageSize: 20/);
  assert.doesNotMatch(viewer, /boletas\.update|tickets\.update|history\.restore/);
  assert.match(read('src/styles/routes/tickets.js'), /ticket-history.css/);
  assert.match(styles, /\.ticket-history-launch:hover/);
  assert.match(styles, /max-width: 760px/);
  assert.match(styles, /max-width: 600px/);
  assert.match(styles, /max-width: 390px/);
  assert.match(styles, /prefers-reduced-motion/);
  assert.match(styles, /ticket-history-review__switch button\.is-active/);
  assert.match(styles, /ticket-history-diff__row--changed/);
  assert.match(styles, /ticket-history-diff__cell--before/);
  assert.match(styles, /ticket-history-diff__cell--after/);
  assert.match(styles, /ticket-history-value-chip/);
  assert.match(styles, /ticket-history-diff__mobile-label/);
});
